import fs from "node:fs";
import path from "node:path";
import solc from "solc";

const root = path.resolve(import.meta.dirname, "..");
const source = fs.readFileSync(path.join(root, "contracts/EoaSell.sol"), "utf8");
const input = {
  language: "Solidity",
  sources: { "EoaSell.sol": { content: source } },
  settings: {
    optimizer: { enabled: true, runs: 200 },
    outputSelection: {
      "*": { "*": ["abi", "evm.deployedBytecode.object"] },
    },
  },
};

const output = JSON.parse(solc.compile(JSON.stringify(input)));
if (output.errors?.some((e) => e.severity === "error")) {
  console.error(output.errors);
  process.exit(1);
}

const contract = output.contracts["EoaSell.sol"].EoaSell;
const bytecode = "0x" + contract.evm.deployedBytecode.object;
const abi = contract.abi;
const outDir = path.join(root, "src/generated");
fs.mkdirSync(outDir, { recursive: true });
const file = `// Generated by scripts/compile-probe.js. Do not edit.
export const eoaSellAbi = ${JSON.stringify(abi, null, 2)};

export const eoaSellBytecode = "${bytecode}";
`;
fs.writeFileSync(path.join(outDir, "eoaSell.js"), file);
console.log("wrote src/generated/eoaSell.js", bytecode.length, "chars");
